testthat::test_that("workflow navigation is advisory-first with explicit technical blockers", {
  root<-getOption("vetblcm.root",".")
  layout<-paste(readLines(file.path(root,"modules","mod_layout.R"),warn=FALSE,encoding="UTF-8"),collapse="\n")
  server<-paste(readLines(file.path(root,"modules","mod_server.R"),warn=FALSE,encoding="UTF-8"),collapse="\n")
  testthat::expect_match(layout,'uiOutput\\("workflow_gate"\\)')
  testthat::expect_match(layout,'uiOutput\\("workflow_nav"\\)')
  testthat::expect_match(server,'page_validation<-function')
  testthat::expect_match(server,'page_hard_blockers<-function')
  testthat::expect_false(grepl('max_unlocked',server,fixed=TRUE))
  testthat::expect_match(server,'Next remains available')
  testthat::expect_match(server,'review_results')
  testthat::expect_match(server,'review_agreement')
  testthat::expect_match(server,'review_publication')
  testthat::expect_match(layout,'ui_page\\("publication"')
})
